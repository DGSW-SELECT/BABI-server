package com.select.domain.user.service;

import com.select.domain.baby.entity.BabyMember;
import com.select.domain.baby.entity.BabyRole;
import com.select.domain.baby.repository.BabyMemberRepository;
import com.select.domain.baby.request.BabyCreateRequest;
import com.select.domain.baby.service.BabyService;
import com.select.domain.user.entity.User;
import com.select.domain.user.repository.UserRepository;
import com.select.global.security.jwt.JwtProvider;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import tools.jackson.databind.ObjectMapper;
import java.net.URI;
import java.net.http.*;
import java.time.LocalDate;
import java.util.Map;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

@ActiveProfiles("test")
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@EnabledIfEnvironmentVariable(named = "BABI_REDIS_TEST_PORT", matches = "[0-9]+")
class AccountLifecycleIntegrationTest {
    @DynamicPropertySource static void redis(DynamicPropertyRegistry registry) {
        registry.add("spring.data.redis.host", () -> "127.0.0.1");
        registry.add("spring.data.redis.port", () -> System.getenv("BABI_REDIS_TEST_PORT"));
    }
    @Autowired UserRepository users;
    @Autowired BabyMemberRepository members;
    @Autowired BabyService babies;
    @Autowired JwtProvider jwt;
    @Autowired PasswordEncoder passwords;
    @Autowired JdbcTemplate jdbc;
    @Autowired AccountLifecycleService accountLifecycle;
    @Autowired org.springframework.transaction.PlatformTransactionManager transactions;
    @Autowired ObjectMapper json;
    @LocalServerPort int port;
    HttpClient client = HttpClient.newHttpClient();
    @BeforeEach void schema() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS family_invitations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, inviter_user_id BIGINT NOT NULL, invited_user_id BIGINT NOT NULL, status VARCHAR(20) NOT NULL)");
    }
    User user() {
        return users.saveAndFlush(User.builder().email(UUID.randomUUID()+"@example.invalid").nickname("test").passwordHash(passwords.encode("Test1234!")).build());
    }
    HttpResponse<String> request(String method, String path, String token, String body) throws Exception {
        var b = HttpRequest.newBuilder(URI.create("http://127.0.0.1:"+port+path)).header("Authorization", "Bearer "+token);
        if (body == null) b.method(method, HttpRequest.BodyPublishers.noBody());
        else b.header("Content-Type","application/json").method(method,HttpRequest.BodyPublishers.ofString(body));
        return client.send(b.build(), HttpResponse.BodyHandlers.ofString());
    }
    @Test void logoutRevokesOnlyCurrentToken() throws Exception {
        User u = user(); String first=jwt.createAccessToken(u.getId().toString()); String second=jwt.createAccessToken(u.getId().toString());
        assertNotEquals(first, second);
        assertEquals(200, request("POST","/auth/logout",first,null).statusCode());
        assertEquals(401, request("GET","/babies",first,null).statusCode());
        assertEquals(200, request("GET","/babies",second,null).statusCode());
    }
    @Test void withdrawalAnonymizesAndRejectsAllTokens() throws Exception {
        User u=user(); String oldEmail=u.getEmail(); String token=jwt.createAccessToken(u.getId().toString());
        assertEquals(200, request("DELETE","/auth/account",token,json.writeValueAsString(Map.of("password","Test1234!"))).statusCode());
        assertEquals(401, request("GET","/babies",token,null).statusCode());
        var stored=users.findById(u.getId()).orElseThrow();
        assertFalse(stored.isActive()); assertNotNull(stored.getWithdrawnAt());
        assertFalse(users.existsByEmail(oldEmail)); assertEquals("!",stored.getPasswordHash());
    }
    @Test void withdrawalAndBabyCreationAreSerialized() throws Exception {
        User u = user();
        var locked = new java.util.concurrent.CountDownLatch(1);
        var release = new java.util.concurrent.CountDownLatch(1);
        try (var executor = java.util.concurrent.Executors.newFixedThreadPool(2)) {
            var withdrawal = executor.submit(() -> new org.springframework.transaction.support.TransactionTemplate(transactions).executeWithoutResult(status -> {
                users.findByIdForUpdate(u.getId()).orElseThrow(); locked.countDown();
                try { assertTrue(release.await(5, java.util.concurrent.TimeUnit.SECONDS)); }
                catch (InterruptedException e) { Thread.currentThread().interrupt(); throw new IllegalStateException(e); }
                accountLifecycle.withdraw(u.getId(), "Test1234!");
            }));
            try {
                assertTrue(locked.await(5, java.util.concurrent.TimeUnit.SECONDS));
                var create = executor.submit(() -> babies.createBaby(new BabyCreateRequest("baby", LocalDate.of(2025,1,1)), u.getId()));
                assertThrows(java.util.concurrent.TimeoutException.class, () -> create.get(300, java.util.concurrent.TimeUnit.MILLISECONDS));
                release.countDown(); withdrawal.get(5, java.util.concurrent.TimeUnit.SECONDS);
                var failure = assertThrows(java.util.concurrent.ExecutionException.class, () -> create.get(5, java.util.concurrent.TimeUnit.SECONDS));
                assertInstanceOf(org.springframework.security.access.AccessDeniedException.class, failure.getCause());
            } finally { release.countDown(); }
        }
    }

    @Test void ownerMustTransferBeforeWithdrawalAndBadPasswordDoesNotDelete() throws Exception {
        User owner=user(), guest=user(); long babyId=babies.createBaby(new BabyCreateRequest("baby", LocalDate.of(2025,1,1)), owner.getId()).babyId();
        members.saveAndFlush(BabyMember.builder().babyId(babyId).userId(guest.getId()).role(BabyRole.GUARDIAN).build());
        String token=jwt.createAccessToken(owner.getId().toString());
        assertEquals(400, request("DELETE","/auth/account",token,json.writeValueAsString(Map.of("password","wrong"))).statusCode());
        assertEquals(409, request("DELETE","/auth/account",token,json.writeValueAsString(Map.of("password","Test1234!"))).statusCode());
        assertTrue(users.findById(owner.getId()).orElseThrow().isActive());
        babies.transferOwnership(babyId,owner.getId(),guest.getId());
        assertEquals(200, request("DELETE","/auth/account",token,json.writeValueAsString(Map.of("password","Test1234!"))).statusCode());
        assertFalse(members.existsByBabyIdAndUserId(babyId,owner.getId()));
    }
}
